use anyhow::Result;
use convert_case::{Case, Casing};
use esdm::EsdmDoc;
use std::fs;
use std::path::PathBuf;

pub fn generate_typescript(out_dir: &PathBuf, docs: &[EsdmDoc]) -> Result<()> {
    let mut types_content = String::new();
    types_content.push_str("// Auto-generated by chromatofoor-gen\n\n");

    let mut commands: Vec<(&str, &str, &str)> = Vec::new(); // (bounded_context, name, pascal_name)
    let mut queries: Vec<(&str, &str, &str)> = Vec::new(); // (bounded_context, name, pascal_name)

    for doc in docs {
        if doc.kind == "entity" || doc.kind == "value-object" || doc.kind == "read-model" {
            let name = doc.name.to_case(Case::Pascal);
            types_content.push_str(&format!("export interface {name} {{\n"));

            if let Some(data) = &doc.data {
                for (prop_name, prop_schema) in &data.properties {
                    let required = data.required.contains(prop_name);
                    let opt_mark = if required { "" } else { "?" };
                    let ts_type = get_ts_type(prop_schema);
                    let prop_key = if prop_name.contains('-') {
                        format!("'{prop_name}'")
                    } else {
                        prop_name.clone()
                    };
                    types_content.push_str(&format!("  {prop_key}{opt_mark}: {ts_type};\n"));
                }
            } else if let Some(schema) = &doc.schema {
                for (prop_name, prop_schema) in &schema.properties {
                    let required = schema.required.contains(prop_name);
                    let opt_mark = if required { "" } else { "?" };
                    let ts_type = get_ts_type(prop_schema);
                    let prop_key = if prop_name.contains('-') {
                        format!("'{prop_name}'")
                    } else {
                        prop_name.clone()
                    };
                    types_content.push_str(&format!("  {prop_key}{opt_mark}: {ts_type};\n"));
                }
            }

            types_content.push_str("}\n\n");
        } else if doc.kind == "command" {
            let pascal_name = doc.name.to_case(Case::Pascal);
            let name = format!("{pascal_name}Command");
            let bc = doc
                .scope
                .as_ref()
                .and_then(|s| s.bounded_context.as_deref())
                .unwrap_or("default");
            commands.push((bc, doc.name.as_str(), doc.name.to_case(Case::Pascal).leak()));

            types_content.push_str(&format!("export interface {name} {{\n"));
            if let Some(data) = &doc.data {
                for (prop_name, prop_schema) in &data.properties {
                    let required = data.required.contains(prop_name);
                    let opt_mark = if required { "" } else { "?" };
                    let ts_type = get_ts_type(prop_schema);
                    let prop_key = if prop_name.contains('-') {
                        format!("'{prop_name}'")
                    } else {
                        prop_name.clone()
                    };
                    types_content.push_str(&format!("  {prop_key}{opt_mark}: {ts_type};\n"));
                }
            }
            types_content.push_str("}\n\n");
        } else if doc.kind == "event" {
            let name = format!("{}Event", doc.name.to_case(Case::Pascal));
            types_content.push_str(&format!("export interface {name} {{\n"));
            if let Some(data) = &doc.data {
                for (prop_name, prop_schema) in &data.properties {
                    let required = data.required.contains(prop_name);
                    let opt_mark = if required { "" } else { "?" };
                    let ts_type = get_ts_type(prop_schema);
                    let prop_key = if prop_name.contains('-') {
                        format!("'{prop_name}'")
                    } else {
                        prop_name.clone()
                    };
                    types_content.push_str(&format!("  {prop_key}{opt_mark}: {ts_type};\n"));
                }
            }
            types_content.push_str("}\n\n");
        } else if doc.kind == "query" {
            let pascal_name = doc.name.to_case(Case::Pascal);
            let name = format!("{pascal_name}Query");
            let bc = doc
                .scope
                .as_ref()
                .and_then(|s| s.bounded_context.as_deref())
                .unwrap_or("default");
            queries.push((bc, doc.name.as_str(), doc.name.to_case(Case::Pascal).leak()));

            types_content.push_str(&format!("export interface {name} {{\n"));
            if let Some(params) = &doc.parameters {
                for (param_name, param_schema) in &params.properties {
                    let required = params.required.contains(param_name);
                    let opt_mark = if required { "" } else { "?" };
                    let ts_type = get_ts_type(param_schema);
                    let prop_key = if param_name.contains('-') {
                        format!("'{param_name}'")
                    } else {
                        param_name.clone()
                    };
                    types_content.push_str(&format!("  {prop_key}{opt_mark}: {ts_type};\n"));
                }
            }
            types_content.push_str("}\n\n");
        }
    }

    // Generate bridge.ts
    let bridge_content = r"// Auto-generated by chromatofoor-gen

export interface CloudEvent<T = any> {
  id: string;
  source: string;
  specversion: string;
  type: string;
  datacontenttype: string;
  time: string;
  data: T;
}

export interface ChromatofoorBridge {
  invoke<T = any>(commandName: string, payload: unknown): Promise<T>;
  query<T = any>(queryName: string, params: unknown): Promise<T>;
  subscribe(eventName: string, handler: (event: CloudEvent) => void): () => void;
}

export class TauriBridge implements ChromatofoorBridge {
  async invoke<T = any>(commandName: string, payload: unknown): Promise<T> {
    const tauri = (window as any).__TAURI__ || (window as any).__TAURI_INTERNALS__;
    if (tauri?.core?.invoke) {
      return tauri.core.invoke('execute_command', { commandName, payload });
    }
    if (tauri?.invoke) {
      return tauri.invoke('execute_command', { commandName, payload });
    }
    throw new Error('Tauri API not found on window.__TAURI__');
  }

  async query<T = any>(queryName: string, params: unknown): Promise<T> {
    const tauri = (window as any).__TAURI__ || (window as any).__TAURI_INTERNALS__;
    if (tauri?.core?.invoke) {
      return tauri.core.invoke('execute_query', { queryName, params });
    }
    if (tauri?.invoke) {
      return tauri.invoke('execute_query', { queryName, params });
    }
    throw new Error('Tauri API not found on window.__TAURI__');
  }

  subscribe(eventName: string, handler: (event: CloudEvent) => void): () => void {
    const tauri = (window as any).__TAURI__ || (window as any).__TAURI_INTERNALS__;
    let unlistenFn: (() => void) | null = null;
    if (tauri?.event?.listen) {
      tauri.event.listen(eventName, (e: any) => handler(e.payload)).then((fn: any) => { unlistenFn = fn; });
    }
    return () => { if (unlistenFn) unlistenFn(); };
  }
}

export class WebBridge implements ChromatofoorBridge {
  constructor(private baseUrl: string = '') {}

  async invoke<T = any>(commandName: string, payload: unknown): Promise<T> {
    const res = await fetch(`${this.baseUrl}/api/rpc`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ command: commandName, payload }),
    });
    if (!res.ok) {
      const err = await res.text();
      throw new Error(err || `RPC command failed: ${res.status}`);
    }
    return res.json();
  }

  async query<T = any>(queryName: string, params: unknown): Promise<T> {
    const res = await fetch(`${this.baseUrl}/api/rpc`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ query: queryName, params }),
    });
    if (!res.ok) {
      const err = await res.text();
      throw new Error(err || `RPC query failed: ${res.status}`);
    }
    return res.json();
  }

  subscribe(eventName: string, handler: (event: CloudEvent) => void): () => void {
    const es = new EventSource(`${this.baseUrl}/api/events?event=${encodeURIComponent(eventName)}`);
    es.onmessage = (msg) => {
      try {
        const parsed = JSON.parse(msg.data);
        handler(parsed);
      } catch (e) {
        console.error('Failed to parse SSE event payload:', e);
      }
    };
    return () => es.close();
  }
}

export class MockBridge implements ChromatofoorBridge {
  private listeners: Map<string, Set<(event: CloudEvent) => void>> = new Map();

  async invoke<T = any>(_commandName: string, _payload: unknown): Promise<T> {
    return {} as T;
  }

  async query<T = any>(_queryName: string, _params: unknown): Promise<T> {
    return {} as T;
  }

  subscribe(eventName: string, handler: (event: CloudEvent) => void): () => void {
    if (!this.listeners.has(eventName)) {
      this.listeners.set(eventName, new Set());
    }
    this.listeners.get(eventName)!.add(handler);
    return () => {
      this.listeners.get(eventName)?.delete(handler);
    };
  }

  emitMockEvent(event: CloudEvent): void {
    const set = this.listeners.get(event.type);
    if (set) {
      set.forEach((h) => h(event));
    }
  }
}
";

    // Generate client.ts
    let mut client_content = String::new();
    client_content.push_str("// Auto-generated by chromatofoor-gen\n\n");
    client_content.push_str("import { ChromatofoorBridge } from './bridge';\n");
    client_content.push_str("import * as Types from './types';\n\n");
    client_content.push_str("export class DomainClient {\n");
    client_content.push_str("  constructor(private bridge: ChromatofoorBridge) {}\n\n");

    for (bc, cmd_name, pascal_name) in &commands {
        let method_name = pascal_name.to_case(Case::Camel);
        let cmd_type = format!("Types.{pascal_name}Command");
        client_content.push_str(&format!(
            "  async {method_name}(payload: {cmd_type}): Promise<void> {{\n    return this.bridge.invoke('{bc}.{cmd_name}', payload);\n  }}\n\n"
        ));
    }

    for (bc, query_name, pascal_name) in &queries {
        let method_name = pascal_name.to_case(Case::Camel);
        let query_type = format!("Types.{pascal_name}Query");
        client_content.push_str(&format!(
            "  async {method_name}(params: {query_type}): Promise<any> {{\n    return this.bridge.query('{bc}.{query_name}', params);\n  }}\n\n"
        ));
    }

    client_content.push_str("}\n");

    // Generate domain.svelte.ts for Svelte 5 Runes
    let mut svelte_content = String::new();
    svelte_content.push_str("// Auto-generated by chromatofoor-gen for Svelte 5 (Runes)\n");
    svelte_content.push_str("import { ChromatofoorBridge } from './bridge';\n");
    svelte_content.push_str("import * as Types from './types';\n\n");
    svelte_content
        .push_str("export type ActionStatus = 'idle' | 'pending' | 'success' | 'error';\n\n");

    svelte_content.push_str(
        r"export function createCommandState<T extends Record<string, any>>(
  bridge: ChromatofoorBridge,
  commandName: string,
  initialValues: T
) {
  let form = $state<T>({ ...initialValues });
  let status = $state<ActionStatus>('idle');
  let error = $state<string | null>(null);

  return {
    get form() { return form; },
    get status() { return status; },
    get error() { return error; },
    reset() {
      form = { ...initialValues };
      status = 'idle';
      error = null;
    },
    async dispatch(): Promise<any> {
      status = 'pending';
      error = null;
      try {
        const res = await bridge.invoke(commandName, form);
        status = 'success';
        return res;
      } catch (err: any) {
        status = 'error';
        error = typeof err === 'string' ? err : err?.message || JSON.stringify(err);
        throw err;
      }
    }
  };
}

export function createQueryState<TParams extends Record<string, any>, TResult = any>(
  bridge: ChromatofoorBridge,
  queryName: string,
  initialParams: TParams
) {
  let params = $state<TParams>({ ...initialParams });
  let data = $state<TResult | null>(null);
  let loading = $state<boolean>(false);
  let error = $state<string | null>(null);

  async function refetch() {
    loading = true;
    error = null;
    try {
      data = await bridge.query<TResult>(queryName, params);
    } catch (err: any) {
      error = typeof err === 'string' ? err : err?.message || JSON.stringify(err);
    } finally {
      loading = false;
    }
  }

  return {
    get params() { return params; },
    get data() { return data; },
    get loading() { return loading; },
    get error() { return error; },
    refetch,
  };
}

",
    );

    for (bc, cmd_name, pascal_name) in &commands {
        let fn_name = format!("create{pascal_name}CommandState");
        let cmd_type = format!("Types.{pascal_name}Command");
        svelte_content.push_str(&format!(
            "export function {fn_name}(bridge: ChromatofoorBridge, initialValues?: Partial<{cmd_type}>) {{\n  return createCommandState<{cmd_type}>(bridge, '{bc}.{cmd_name}', (initialValues || {{}}) as {cmd_type});\n}}\n\n"
        ));
    }

    for (bc, query_name, pascal_name) in &queries {
        let fn_name = format!("create{pascal_name}QueryState");
        let query_type = format!("Types.{pascal_name}Query");
        svelte_content.push_str(&format!(
            "export function {fn_name}(bridge: ChromatofoorBridge, initialParams?: Partial<{query_type}>) {{\n  return createQueryState<{query_type}>(bridge, '{bc}.{query_name}', (initialParams || {{}}) as {query_type});\n}}\n\n"
        ));
    }

    // Generate index.ts
    let index_content = r"// Auto-generated by chromatofoor-gen
export * from './types';
export * from './bridge';
export * from './client';
export * from './domain.svelte';
";

    // Write to typescript-client directory
    let ts_client_dir = out_dir.join("typescript-client");
    fs::create_dir_all(&ts_client_dir)?;
    fs::write(ts_client_dir.join("types.ts"), &types_content)?;
    fs::write(ts_client_dir.join("bridge.ts"), bridge_content)?;
    fs::write(ts_client_dir.join("client.ts"), &client_content)?;
    fs::write(ts_client_dir.join("domain.svelte.ts"), &svelte_content)?;
    fs::write(ts_client_dir.join("index.ts"), index_content)?;

    Ok(())
}

fn get_ts_type(schema: &esdm::PropertySchema) -> String {
    if let Some(ref_path) = &schema.ref_path {
        let parts: Vec<&str> = ref_path.split('/').collect();
        if let Some(last) = parts.last() {
            return last.to_case(Case::Pascal);
        }
    }

    if let Some(t) = &schema.prop_type {
        match t.as_str() {
            "string" => "string".to_string(),
            "integer" | "number" => "number".to_string(),
            "boolean" => "boolean".to_string(),
            "array" => {
                if let Some(items) = &schema.items {
                    format!("{}[]", get_ts_type(items))
                } else {
                    "any[]".to_string()
                }
            }
            "object" => "Record<string, any>".to_string(),
            _ => "any".to_string(),
        }
    } else {
        "any".to_string()
    }
}
